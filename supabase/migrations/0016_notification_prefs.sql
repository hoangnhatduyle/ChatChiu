-- One row per user. Missing row = defaults (UTC, 9:00, alerts on, theme system).
create table public.user_preferences (
  user_id                 uuid primary key references auth.users(id) on delete cascade,
  timezone                text not null default 'UTC',
  notify_hour             integer not null default 9 check (notify_hour between 0 and 23),
  expiry_alerts           boolean not null default true,
  low_stock_alerts        boolean not null default true,
  theme                   text not null default 'system' check (theme in ('system', 'light', 'dark')),
  -- Her local date of the last expiry-reminder run: at most one per local day (AC-API-18).
  last_expiry_reminder_on date,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

alter table public.user_preferences enable row level security;
create policy "user_preferences_owner_select" on public.user_preferences for select using (auth.uid() = user_id);
create policy "user_preferences_owner_insert" on public.user_preferences for insert with check (auth.uid() = user_id);
create policy "user_preferences_owner_update" on public.user_preferences for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "user_preferences_owner_delete" on public.user_preferences for delete using (auth.uid() = user_id);

create trigger trg_user_preferences_updated_at
  before update on public.user_preferences
  for each row execute function public.set_updated_at();

-- Reject an unknown IANA zone at write time, so the send job and the stats never
-- fail on a bad stored value (the API validates too).
create function public.check_user_timezone()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform now() at time zone new.timezone;
  return new;
exception when invalid_parameter_value then
  raise exception 'unknown time zone: %', new.timezone using errcode = '22023';
end;
$$;

create trigger trg_user_preferences_timezone
  before insert or update of timezone on public.user_preferences
  for each row execute function public.check_user_timezone();

revoke all on function public.check_user_timezone() from public, anon, authenticated;
revoke all on public.user_preferences from anon;

-- Set when a low-stock push is sent; cleared by a restock (AC-API-19, AC-DATA-10).
alter table public.inventory_items
  add column if not exists low_stock_notified_at timestamptz;

-- Which delivery path a device uses, so the server only pushes to web-push
-- devices and the Fire shell notifies itself (architecture.md §6.4). Existing
-- and old-app rows get 'web-push'.
alter table public.push_subscriptions
  add column if not exists channel text not null default 'web-push'
    check (channel in ('web-push', 'local'));

-- Send failures, readable by their owner (AC-API-20, NC-NT-NO-SILENT-FAILURE).
-- Written only by the send job with the service role: no insert/update policy.
create table public.push_failures (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  endpoint    text not null,
  status_code integer,
  message     text not null,
  created_at  timestamptz not null default now()
);

create index idx_push_failures_user_created on public.push_failures (user_id, created_at desc);

alter table public.push_failures enable row level security;
create policy "push_failures_owner_select" on public.push_failures for select using (auth.uid() = user_id);
-- Defence in depth on top of RLS: users may only read; anon nothing.
revoke all on public.push_failures from anon;
revoke insert, update, delete, truncate on public.push_failures from authenticated;
